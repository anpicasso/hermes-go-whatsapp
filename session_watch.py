def tool(args: dict, **_: Any) -> str:
    """Tool adapter; destination comes exclusively from Hermes' runtime context."""
    try:
        from gateway.session_context import bound_session_key, get_session_env

        if not isinstance(args, dict) or set(args) - {"action", "device_id", "chat_jid", "minutes", "message_id"}:
            raise WatchError("unsupported watch arguments; destination cannot be supplied")
        key = bound_session_key()  # Never borrow a process-global route from os.environ.
        session_id = get_session_env("HERMES_SESSION_ID")
        if not key or not session_id:
            raise WatchError("no trusted session context; use this tool in a gateway conversation")
        action = args.get("action")
        followup: dict[str, Any] | None = None
        if action == "start":
            if set(args) - {"action", "device_id", "chat_jid", "minutes"}:
                raise WatchError("start accepts only device_id, chat_jid, and minutes")
            minutes = args.get("minutes", DEFAULT_MINUTES)
            if type(minutes) is not int:
                raise WatchError("minutes must be an integer")
            result = arm_watch(args.get("device_id"), args.get("chat_jid"), minutes,
                               session_key=key, session_id=session_id)
        elif action in ("status", "stop"):
            if set(args) != {"action"}:
                raise WatchError("status and stop accept only action")
            result = (watch_status if action == "status" else stop_watch)(session_key=key, session_id=session_id)
        elif action in ("wait", "handled"):
            if set(args) != {"action", "message_id"}:
                raise WatchError(f"{action} accepts action and message_id only")
            if action == "wait":
                followup = arm_followup(key, session_id, args.get("message_id"))
                result = (
                    f"follow-up armed for message {followup['message_id']} "
                    f"(watch {followup['watch_ref']}, generation {followup['generation']}) "
                    f"due {followup['due_iso']}"
                )
            else:
                result = mark_handled(key, session_id, args.get("message_id"))
        else:
            raise WatchError("action must be start, status, stop, wait, or handled")
        payload: dict[str, Any] = {"ok": True, "action": action, "mode": "wait_report", "message": result}
        if followup is not None:
            payload["followup"] = followup
        return json.dumps(payload)
    except WatchError as exc:
        return json.dumps({"ok": False, "error": str(exc)})
    except Exception as exc:
        logger.warning("gowa-watch tool failed (%s)", type(exc).__name__)
        return json.dumps({"ok": False, "error": "watch tool unavailable or internal error"})


_USAGE = "usage: /gowa-watch start <session_id> <chat_jid> [minutes] | status | stop"


async def command(raw_args: str = "", *, session_key: str = "", session_id: str = "", source: Any = None, **_: Any) -> str:
    """``/gowa-watch`` handler; bound only to the dispatching conversation's session."""
    parts = (raw_args or "").split()
    if not parts:
        return _USAGE
    action = parts[0].lower()
    try:
        if action == "start":
            if not 3 <= len(parts) <= 4:
                return _USAGE
            return await asyncio.to_thread(
                arm_watch,
                parts[1],
                parts[2],
                parts[3] if len(parts) == 4 else DEFAULT_MINUTES,
                session_key=session_key,
                session_id=session_id,
            )
        if action == "status" and len(parts) == 1:
            return await asyncio.to_thread(watch_status, session_key=session_key, session_id=session_id)
        if action == "stop" and len(parts) == 1:
            return await asyncio.to_thread(stop_watch, session_key=session_key, session_id=session_id)
        return _USAGE
    except WatchError as exc:
        return f"gowa-watch: {exc}"
    except Exception as exc:
        logger.warning("gowa-watch command failed (%s)", type(exc).__name__)
        return "gowa-watch: internal error"
