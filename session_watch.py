def _parse_payload(raw: Any) -> tuple[str, str, str, str]:
    if not isinstance(raw, dict):
        raise WatchError("payload is not an object")
    if raw.get("event") != "message":
        raise WatchError("event is not message")
    slot = _session_slot(raw.get("session_id"))
    payload = raw.get("payload")
    if not isinstance(payload, dict):
        raise WatchError("payload body is not an object")
    if payload.get("is_from_me") is not False:
        raise WatchError("outbound or unclassified message")
    chat = _chat_jid(payload.get("chat_id"))
    message_id = _clean(payload.get("id"), "message id")
    body = payload.get("body")
    if not isinstance(body, str):
        raise WatchError("message has no text body")
    body = "".join(ch for ch in body if ch in "\n\t" or 32 <= ord(ch) != 127).strip()
    if not body:
        raise WatchError("message has no text body")
    if len(body) > MAX_BODY:
        body = body[:MAX_BODY] + "\n[truncated]"
    return slot, chat, message_id, body


def _supervisor_alive() -> bool:
    if _SUPERVISOR_TASK is None or _SUPERVISOR_TASK.done():
        return False
    return _GATEWAY_LOOP is None or _GATEWAY_LOOP.is_running()


def _supervisor_done(task: asyncio.Task) -> None:
    global _SUPERVISOR_TASK
    if _SUPERVISOR_TASK is task:
        _SUPERVISOR_TASK = None
    if task.cancelled():
        return
    try:
        exc = task.exception()
    except Exception:
        return
    if exc is not None:
        logger.warning("gowa watch: follow-up supervisor stopped (%s)", type(exc).__name__)


def _ensure_supervisor(store: Any) -> bool:
    """Start the single gateway-owned follow-up task. Call on the gateway loop."""
    global _SUPERVISOR_TASK, _SUPERVISOR_WAKE
    if _supervisor_alive():
        return True
    if _SUPERVISOR_WAKE is None:
        _SUPERVISOR_WAKE = asyncio.Event()
    coro = _supervise(store)
    try:
        spawn = getattr(_CTX, "spawn_task", None)
        if callable(spawn):
            task: Any = spawn(coro, name="gowa-watch-followup")
        else:
            task = asyncio.get_running_loop().create_task(coro, name="gowa-watch-followup")
    except Exception as exc:
        coro.close()
        logger.warning("gowa watch: could not start follow-up supervisor (%s)", type(exc).__name__)
        return False
    _SUPERVISOR_TASK = task
    task.add_done_callback(_supervisor_done)
    return True


def _ensure_supervisor_sync() -> bool:
    """Ensure the gateway task from a tool thread without owning a timer there."""
    if _supervisor_alive():
        return True
    if _SESSION_STORE is None:
        return False
    try:
        running = asyncio.get_running_loop()
    except RuntimeError:
        running = None
    if running is not None and (running is _GATEWAY_LOOP or _GATEWAY_LOOP is None):
        return _ensure_supervisor(_SESSION_STORE)
    loop = _GATEWAY_LOOP
    if loop is None or loop.is_closed() or not loop.is_running():
        return False

    async def _start() -> bool:
        return _ensure_supervisor(_SESSION_STORE)

    try:
        return bool(asyncio.run_coroutine_threadsafe(_start(), loop).result(timeout=5))
    except Exception as exc:
        logger.warning("gowa watch: follow-up scheduler start failed (%s)", type(exc).__name__)
        return False


def _wake_supervisor() -> None:
    event = _SUPERVISOR_WAKE
    loop = _GATEWAY_LOOP
    if event is None or loop is None or loop.is_closed():
        return
    try:
        running = asyncio.get_running_loop()
    except RuntimeError:
        running = None
    try:
        if running is loop:
            event.set()
        else:
            loop.call_soon_threadsafe(event.set)
    except RuntimeError:
        pass


async def _sleep_until(seconds: float) -> None:
    global _SUPERVISOR_WAKE
    if _SUPERVISOR_WAKE is None:
        _SUPERVISOR_WAKE = asyncio.Event()
    event = _SUPERVISOR_WAKE
    event.clear()
    try:
        await asyncio.wait_for(event.wait(), timeout=max(0.0, seconds))
    except asyncio.TimeoutError:
        pass


async def _deliver_followup(watch: sqlite3.Row, store: Any) -> None:
    generation = int(watch["generation"])
    message_id = str(watch["followup_message_id"])
    claimed = await asyncio.to_thread(_claim_followup, generation, message_id)
    if claimed is None:
        return
    if store is None:
        await asyncio.to_thread(_finish_followup, generation, message_id, "failed")
        logger.warning("gowa watch: follow-up failed (session store unavailable)")
        return
    try:
        entry = await asyncio.to_thread(store.lookup_by_session_key, claimed["session_key"])
    except Exception as exc:
        logger.warning("gowa watch: follow-up session lookup failed (%s)", type(exc).__name__)
        await asyncio.to_thread(_retry_followup, generation, message_id)
        return
    if entry is None:
        await asyncio.to_thread(_drop_watch, claimed["session_key"], claimed["session_id"])
        logger.info("gowa watch: stopped (bound session is gone)")
        return
    if getattr(entry, "session_id", "") != claimed["session_id"]:
        await asyncio.to_thread(_drop_watch, claimed["session_key"], claimed["session_id"])
        logger.info("gowa watch: stopped (bound session changed, likely /new)")
        return
    if not await asyncio.to_thread(_followup_current, generation, message_id):
        logger.info("gowa watch: skipped stale follow-up (watch or message changed)")
        return
    if _CTX is None:
        await asyncio.to_thread(_retry_followup, generation, message_id)
        return
    try:
        accepted = bool(
            _CTX.inject_message(
                _render_followup(claimed, claimed["last_message_at"]),
                session_key=claimed["session_key"],
            )
        )
    except Exception as exc:
        accepted = False
        logger.warning("gowa watch: follow-up injection failed (%s)", type(exc).__name__)
    if accepted:
        await asyncio.to_thread(_finish_followup, generation, message_id, "delivered")
        logger.info("gowa watch: follow-up delivered into the armed session")
    else:
        state = await asyncio.to_thread(_retry_followup, generation, message_id)
        logger.warning("gowa watch: follow-up injection refused (%s)", state)
        if state == "pending":
            _wake_supervisor()


async def _supervise(store: Any) -> None:
    """One task owns follow-up timing while any watch is active."""
    try:
        while True:
            if not _enabled():
                return
            row = await asyncio.to_thread(_active_watch)
            if row is None:
                return
            now = _now()
            if row["followup_state"] == "pending" and row["followup_due"] is not None:
                remaining = float(row["followup_due"]) - now
                if remaining > 0:
                    await _sleep_until(remaining)
                    continue
                await _deliver_followup(row, store)
                continue
            remaining = max(0.0, float(row["expires_at"]) - now)
            await _sleep_until(min(FOLLOWUP_POLL_SECONDS, remaining))
    except asyncio.CancelledError:
        raise
    except Exception as exc:
        logger.warning("gowa watch: follow-up supervisor failed (%s)", type(exc).__name__)


def _remember_runtime(session_store: Any) -> None:
    global _GATEWAY_LOOP, _SESSION_STORE
    try:
        _GATEWAY_LOOP = asyncio.get_running_loop()
    except RuntimeError:
        _GATEWAY_LOOP = None
    _SESSION_STORE = session_store


def shutdown() -> None:
    """Cancel the supervised task on plugin unload; safe from any thread."""
    global _SUPERVISOR_TASK, _SUPERVISOR_WAKE, _GATEWAY_LOOP, _SESSION_STORE
    task = _SUPERVISOR_TASK
    loop = _GATEWAY_LOOP
    if task is not None and not task.done():
        try:
            if loop is not None and loop.is_running():
                loop.call_soon_threadsafe(task.cancel)
            else:
                task.cancel()
        except RuntimeError:
            pass
    _SUPERVISOR_TASK = None
    _SUPERVISOR_WAKE = None
    _GATEWAY_LOOP = None
    _SESSION_STORE = None


async def _handle(event: Any, session_store: Any) -> None:
    try:
        slot, chat, message_id, body = _parse_payload(getattr(event, "raw_message", None))
    except WatchError as exc:
        logger.info("gowa watch: ignored (%s)", exc)
        return

    watch = await asyncio.to_thread(_active_watch)
    if watch is None:
        logger.info("gowa watch: ignored (no active watch)")
        return
    if watch["slot"] != slot or watch["chat_jid"] != chat:
        logger.info("gowa watch: ignored (slot or chat mismatch)")
        return
    if session_store is None:
        logger.warning("gowa watch: session store unavailable")
        return
    try:
        entry = await asyncio.to_thread(session_store.lookup_by_session_key, watch["session_key"])
    except Exception as exc:
        logger.warning("gowa watch: session lookup failed (%s)", type(exc).__name__)
        return
    if entry is None:
        logger.info("gowa watch: ignored (bound session is gone)")
        return
    if getattr(entry, "session_id", "") != watch["session_id"]:
        await asyncio.to_thread(_drop_watch, watch["session_key"], watch["session_id"])
        logger.info("gowa watch: stopped (bound session changed, likely /new)")
        return

    claimed = await asyncio.to_thread(_claim, slot, chat, message_id, watch)
    if not claimed:
        logger.info("gowa watch: ignored (duplicate or watch changed)")
        return
    if _CTX is None:
        await asyncio.to_thread(_release, slot, message_id)
        logger.warning("gowa watch: plugin context unavailable")
        return
    received_at = _now()
    try:
        accepted = bool(
            _CTX.inject_message(
                _render_watch_message(watch, chat, message_id, body, received_at),
                session_key=watch["session_key"],
            )
        )
    except Exception as exc:
        accepted = False
        logger.warning("gowa watch: injection failed (%s)", type(exc).__name__)
    if not accepted:
        await asyncio.to_thread(_release, slot, message_id)
        logger.warning("gowa watch: injection refused; message not marked scheduled")
        return
    await asyncio.to_thread(_mark_scheduled, slot, chat, message_id, int(watch["generation"]))
    _ensure_supervisor(session_store)
    _wake_supervisor()
    logger.info("gowa watch: scheduled into the armed session")


def _owned(event: Any) -> bool:
    source = getattr(event, "source", None)
    if source is None:
        return False
    platform = getattr(source, "platform", None)
    if getattr(platform, "value", platform) != "webhook":
        return False
    if not _enabled():
        return False
    route = _route_name()
    if not route:
        return False
    return getattr(source, "chat_name", None) == f"webhook/{route}"


async def pre_gateway_dispatch(event: Any = None, gateway: Any = None, session_store: Any = None, **_: Any) -> Any:
    """Consume the dedicated route; never fail open into an ordinary webhook LLM run."""
    try:
        _remember_runtime(session_store)
        if _enabled() and not _supervisor_alive():
            # Reload/restart recovery: any inbound in a live gateway can resume an
            # overdue persisted follow-up instead of requiring a new watched message.
            watch = await asyncio.to_thread(_active_watch)
            if watch is not None and session_store is not None:
                _ensure_supervisor(session_store)
    except Exception:
        pass
    try:
        if not _owned(event):
            return None
    except Exception:
        return None
    try:
        await _handle(event, session_store)
    except Exception as exc:
        logger.warning("gowa watch: internal failure on owned route (%s)", type(exc).__name__)
    return {"action": "skip", "reason": "gowa session watch"}


