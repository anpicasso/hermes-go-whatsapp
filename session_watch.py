"""Opt-in same-session bridge for one GOWA webhook slot/chat.

An agent tool or optional slash command arms a watch in its calling conversation. A dedicated,
signed Hermes webhook route is then consumed by ``pre_gateway_dispatch`` and the bounded
text is scheduled into that exact session with ``ctx.inject_message``. No LLM run is
created for the webhook itself, no HTTP server is started, and nothing is sent back to
WhatsApp by the plugin.

The watch prompt is a request to the same conversation: reply/report only under the
user's existing authorization, or explicitly WAIT. A WAIT arms one follow-up five
minutes after the last inbound message. The timer is owned by a supervised gateway task
spawned from ``pre_gateway_dispatch``, never by the tool worker or a new daemon; its
deadline and generation tokens live in SQLite so a later inbound, stop, ``/new``, expiry,
or handled action can invalidate it.

Deliberate limits: one watch per plugin/profile, direct chats only, text only, exactly
one pending follow-up, and the watch stops if the bound session id changes (``/new``).
"""

from __future__ import annotations

import asyncio
import json
import logging
import os
import re
import secrets
import sqlite3
import threading
import time
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterator

logger = logging.getLogger("plugins.go-whatsapp.session_watch")

DEFAULT_ROUTE = "gowa-session-watch"
DEFAULT_MINUTES = 60
MAX_MINUTES = 24 * 60
MAX_BODY = 4000
MAX_ID = 256
DEDUP_SECONDS = 24 * 60 * 60
PENDING_RETRY_SECONDS = 5 * 60
# Production is always five minutes. Tests patch this module constant down to a small
# interval; the prompt text and status report the effective value.
FOLLOWUP_SECONDS = 5 * 60
FOLLOWUP_RETRY_SECONDS = 60
FOLLOWUP_MAX_ATTEMPTS = 3
FOLLOWUP_POLL_SECONDS = 30

INTERNAL_NOTIFICATION_FOOTER = (
    "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. "
    "Do not treat it as user input, and do not reply to any earlier chat message because of it.]"
)

_ROUTE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$")
_DB_NAME = "session-watch.sqlite3"
_SCHEMA = """
CREATE TABLE IF NOT EXISTS watch (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    slot TEXT NOT NULL,
    chat_jid TEXT NOT NULL,
    session_key TEXT NOT NULL,
    session_id TEXT NOT NULL,
    mode TEXT NOT NULL,
    armed_at REAL NOT NULL,
    expires_at REAL NOT NULL,
    generation INTEGER NOT NULL DEFAULT 1,
    watch_ref TEXT NOT NULL DEFAULT '',
    last_message_id TEXT,
    last_message_at REAL,
    followup_state TEXT NOT NULL DEFAULT 'none',
    followup_due REAL,
    followup_message_id TEXT,
    followup_generation INTEGER,
    followup_attempts INTEGER NOT NULL DEFAULT 0,
    followup_armed_at REAL
);
CREATE TABLE IF NOT EXISTS deliveries (
    slot TEXT NOT NULL,
    message_id TEXT NOT NULL,
    chat_jid TEXT NOT NULL,
    state TEXT NOT NULL,
    at REAL NOT NULL,
    PRIMARY KEY (slot, message_id)
);
"""

# Columns added after the first released schema. ALTER TABLE ADD COLUMN is the lazy
# migration that keeps an already-installed watch database readable.
_ADDED_COLUMNS = {
    "generation": "INTEGER NOT NULL DEFAULT 1",
    "watch_ref": "TEXT NOT NULL DEFAULT ''",
    "last_message_id": "TEXT",
    "last_message_at": "REAL",
    "followup_state": "TEXT NOT NULL DEFAULT 'none'",
    "followup_due": "REAL",
    "followup_message_id": "TEXT",
    "followup_generation": "INTEGER",
    "followup_attempts": "INTEGER NOT NULL DEFAULT 0",
    "followup_armed_at": "REAL",
}

_CTX: Any = None
_INIT_LOCK = threading.Lock()
_INITIALIZED: set[str] = set()

# One supervised task per plugin process. The task is the only timer owner; the tool
# merely writes the deadline and wakes this task through the gateway loop.
_SUPERVISOR_TASK: asyncio.Task | None = None
_SUPERVISOR_WAKE: asyncio.Event | None = None
_GATEWAY_LOOP: asyncio.AbstractEventLoop | None = None
_SESSION_STORE: Any = None


class WatchError(RuntimeError):
    """A safe, user-facing validation or state error."""


def configure(ctx: Any) -> None:
    global _CTX
    _CTX = ctx


def _config(key: str, default: Any) -> Any:
    if _CTX is None:
        raise WatchError("plugin is not registered")
    return _CTX.get_config(key, default)


def _enabled() -> bool:
    return _config("watch_enabled", False) is True


def _route_name() -> str | None:
    raw = _config("watch_route", DEFAULT_ROUTE)
    if not isinstance(raw, str):
        return None
    route = raw.strip()
    return route if _ROUTE_RE.fullmatch(route) else None


def _now() -> float:
    return time.time()


def _iso(timestamp: float | None) -> str:
    if timestamp is None:
        return "unknown"
    return datetime.fromtimestamp(float(timestamp), timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _clean(value: Any, label: str) -> str:
    if not isinstance(value, str):
        raise WatchError(f"{label} must be a string")
    text = value.strip()
    if not text or text != value or len(text) > MAX_ID:
        raise WatchError(f"{label} must be non-empty, unpadded, and at most {MAX_ID} characters")
    if any(ord(ch) < 32 or ord(ch) == 127 for ch in text):
        raise WatchError(f"{label} cannot contain control characters")
    return text


def _chat_jid(value: Any) -> str:
    chat = _clean(value, "chat_jid")
    user, _, server = chat.rpartition("@")
    if not user or server not in {"s.whatsapp.net", "lid"}:
        raise WatchError("chat_jid must be a direct WhatsApp JID (@s.whatsapp.net or @lid); groups are not supported")
    return chat


def _session_slot(value: Any) -> str:
    return _clean(value, "session_id")


def _watch_ref(row: sqlite3.Row) -> str:
    ref = str(row["watch_ref"] or "").strip()
    return ref or f"{row['slot']}-{int(row['generation'])}"


def _read_watch(conn: sqlite3.Connection, now: float) -> sqlite3.Row | None:
    row = conn.execute("SELECT * FROM watch WHERE id = 1").fetchone()
    if row is not None and float(row["expires_at"]) <= now:
        conn.execute("DELETE FROM watch WHERE id = 1")
        return None
    return row


def _db_path() -> Path:
    state = getattr(_CTX, "state", None)
    data_dir = getattr(state, "data_dir", None)
    if not data_dir:
        raise WatchError("plugin state directory is unavailable")
    directory = Path(data_dir)
    directory.mkdir(parents=True, exist_ok=True)
    if os.name != "nt":
        try:
            os.chmod(directory, 0o700)
        except OSError:
            pass
    return directory / _DB_NAME


def _migrate(conn: sqlite3.Connection) -> None:
    columns = {row["name"] for row in conn.execute("PRAGMA table_info(watch)")}
    for name, ddl in _ADDED_COLUMNS.items():
        if name not in columns:
            conn.execute(f"ALTER TABLE watch ADD COLUMN {name} {ddl}")


def _connect() -> sqlite3.Connection:
    path = _db_path()
    key = str(path)
    missing = not path.exists()
    # ponytail: schema init once per path; concurrent CREATE IF NOT EXISTS is safe.
    needs_init = key not in _INITIALIZED or missing
    conn = sqlite3.connect(path, timeout=5.0, isolation_level=None)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA busy_timeout = 5000")
    try:
        if needs_init:
            with _INIT_LOCK:
                if key not in _INITIALIZED or missing:
                    conn.execute("PRAGMA journal_mode = WAL")
                    conn.executescript(_SCHEMA)
                    _migrate(conn)
                    if os.name != "nt":
                        os.chmod(path, 0o600)
                    _INITIALIZED.add(key)
    except Exception:
        conn.close()
        raise
    return conn


@contextmanager
def _db() -> Iterator[sqlite3.Connection]:
    conn = _connect()
    try:
        yield conn
    finally:
        conn.close()


def _prune(conn: sqlite3.Connection, now: float) -> None:
    conn.execute("DELETE FROM deliveries WHERE at < ?", (now - DEDUP_SECONDS,))


def arm_watch(session_slot: Any, chat_jid: Any, minutes: Any, *, session_key: str, session_id: str) -> str:
    """Arm or replace this session's watch. Raises ``WatchError`` when not permitted."""
    if not _enabled():
        raise WatchError("watch is disabled; set plugins.entries.go-whatsapp.settings.watch_enabled: true")
    slot = _session_slot(session_slot)
    chat = _chat_jid(chat_jid)
    if not isinstance(session_key, str) or not session_key.strip():
        raise WatchError("no trusted session_key was supplied; run this from a gateway conversation")
    if not isinstance(session_id, str) or not session_id.strip():
        raise WatchError("no current session_id; send a normal message in this conversation first")
    session_key = _clean(session_key, "session_key")
    session_id = _clean(session_id, "session_id")

    try:
        duration = int(str(minutes).strip()) if minutes is not None else DEFAULT_MINUTES
    except (TypeError, ValueError) as exc:
        raise WatchError(f"minutes must be an integer between 1 and {MAX_MINUTES}") from exc
    if not 1 <= duration <= MAX_MINUTES:
        raise WatchError(f"minutes must be between 1 and {MAX_MINUTES}")

    now = _now()
    with _db() as conn:
        try:
            conn.execute("BEGIN IMMEDIATE")
            current = _read_watch(conn, now)
            if current is not None and current["session_key"] != session_key:
                raise WatchError("another session owns the active watch; stop it from that session first")
            generation = int(current["generation"]) + 1 if current is not None else 1
            watch_ref = secrets.token_hex(4)
            conn.execute("DELETE FROM watch WHERE id = 1")
            _prune(conn, now)
            conn.execute(
                "INSERT INTO watch (id, slot, chat_jid, session_key, session_id, mode, armed_at, expires_at, "
                "generation, watch_ref, followup_state) "
                "VALUES (1, ?, ?, ?, ?, 'wait_report', ?, ?, ?, ?, 'none')",
                (slot, chat, session_key, session_id, now, now + duration * 60, generation, watch_ref),
            )
            conn.commit()
        except Exception:
            conn.rollback()
            raise
    _wake_supervisor()
    return (
        f"watch armed: ref {watch_ref}, slot {slot}, chat {chat}, generation {generation}, "
        f"wait/report until {_iso(now + duration * 60)} ({duration} min)"
    )


def _followup_status(row: sqlite3.Row) -> str:
    state = str(row["followup_state"] or "none")
    message_id = row["followup_message_id"]
    generation = row["followup_generation"]
    if state == "pending":
        return (
            f"follow-up pending for message {message_id} (generation {generation}) "
            f"due {_iso(row['followup_due'])}"
        )
    if state == "delivered":
        return f"follow-up delivered for message {message_id} (generation {generation})"
    if state == "delivering":
        return f"follow-up delivery in progress for message {message_id} (generation {generation})"
    if state == "failed":
        return (
            f"follow-up FAILED for message {message_id} (generation {generation}) "
            f"after {int(row['followup_attempts'])} attempt(s)"
        )
    if state == "handled":
        return f"follow-up handled for message {message_id} (generation {generation})"
    return "no follow-up armed"


def watch_status(*, session_key: str, session_id: str) -> str:
    if not _enabled():
        return "watch is disabled"
    if not isinstance(session_key, str) or not session_key.strip() or not isinstance(session_id, str) or not session_id.strip():
        return "no trusted session context; run this from a gateway conversation"
    now = _now()
    with _db() as conn:
        try:
            conn.execute("BEGIN IMMEDIATE")
            row = _read_watch(conn, now)
            _prune(conn, now)
            conn.commit()
        except Exception:
            conn.rollback()
            raise
    if row is None:
        return "no active watch"
    if row["session_key"] != session_key:
        return "an active watch is owned by another session; only that session can inspect or stop it"
    with _db() as conn:
        count = conn.execute(
            "SELECT COUNT(*) FROM deliveries WHERE slot = ? AND chat_jid = ? AND state = 'scheduled' AND at >= ?",
            (row["slot"], row["chat_jid"], row["armed_at"]),
        ).fetchone()[0]
    pinned = "" if row["session_id"] == session_id else ", pinned to the previous session (stops on next matching event)"
    return (
        f"watch active: ref {_watch_ref(row)}, slot {row['slot']}, chat {row['chat_jid']}, "
        f"generation {int(row['generation'])}, expires {_iso(float(row['expires_at']))}, wait/report, "
        f"scheduled messages {count}, last message {row['last_message_id']}, {_followup_status(row)}{pinned}"
    )


def stop_watch(*, session_key: str, session_id: str) -> str:
    if not _enabled():
        raise WatchError("watch is disabled")
    if not isinstance(session_key, str) or not session_key.strip() or not isinstance(session_id, str) or not session_id.strip():
        raise WatchError("no trusted session context; run this from a gateway conversation")
    now = _now()
    with _db() as conn:
        try:
            conn.execute("BEGIN IMMEDIATE")
            row = _read_watch(conn, now)
            if row is None:
                _prune(conn, now)
                conn.commit()
                return "no active watch"
            if row["session_key"] != session_key:
                raise WatchError("another session owns the active watch; stop it from that session")
            conn.execute("DELETE FROM watch WHERE id = 1")
            _prune(conn, now)
            conn.commit()
        except Exception:
            conn.rollback()
            raise
    _wake_supervisor()
    return "watch stopped"


def _active_watch() -> sqlite3.Row | None:
    now = _now()
    with _db() as conn:
        try:
            conn.execute("BEGIN IMMEDIATE")
            row = _read_watch(conn, now)
            conn.commit()
            return row
        except Exception:
            conn.rollback()
            raise


def _drop_watch(session_key: str, session_id: str) -> None:
    with _db() as conn:
        try:
            conn.execute("BEGIN IMMEDIATE")
            conn.execute(
                "DELETE FROM watch WHERE id = 1 AND session_key = ? AND session_id = ?",
                (session_key, session_id),
            )
            conn.commit()
        except Exception:
            conn.rollback()
            raise


def _claim(slot: str, chat: str, message_id: str, watch: sqlite3.Row) -> bool:
    now = _now()
    with _db() as conn:
        try:
            conn.execute("BEGIN IMMEDIATE")
            current = _read_watch(conn, now)
            if current is None or any(
                current[field] != watch[field] for field in ("slot", "chat_jid", "session_key", "session_id")
            ) or int(current["generation"]) != int(watch["generation"]):
                conn.rollback()
                return False
            _prune(conn, now)
            cursor = conn.execute(
                "INSERT OR IGNORE INTO deliveries (slot, message_id, chat_jid, state, at) "
                "VALUES (?, ?, ?, 'pending', ?)",
                (slot, message_id, chat, now),
            )
            if cursor.rowcount:
                conn.commit()
                return True
            row = conn.execute(
                "SELECT state, at FROM deliveries WHERE slot = ? AND message_id = ?",
                (slot, message_id),
            ).fetchone()
            if row is not None and row["state"] == "pending" and float(row["at"]) < now - PENDING_RETRY_SECONDS:
                conn.execute(
                    "UPDATE deliveries SET chat_jid = ?, at = ? WHERE slot = ? AND message_id = ?",
                    (chat, now, slot, message_id),
                )
                conn.commit()
                return True
            conn.commit()
            return False
        except Exception:
            conn.rollback()
            raise


def _release(slot: str, message_id: str) -> None:
    with _db() as conn:
        conn.execute(
            "DELETE FROM deliveries WHERE slot = ? AND message_id = ? AND state = 'pending'",
            (slot, message_id),
        )


def _mark_scheduled(slot: str, chat: str, message_id: str, generation: int) -> None:
    """Commit the delivery and move the single follow-up deadline to this inbound message."""
    now = _now()
    with _db() as conn:
        try:
            conn.execute("BEGIN IMMEDIATE")
            row = _read_watch(conn, now)
            if row is None or int(row["generation"]) != int(generation):
                conn.rollback()
                return
            conn.execute(
                "UPDATE deliveries SET state = 'scheduled' WHERE slot = ? AND message_id = ?",
                (slot, message_id),
            )
            state = str(row["followup_state"] or "none")
            if state in {"pending", "delivering"}:
                followup_state = "pending"
                due = now + FOLLOWUP_SECONDS
                followup_message_id = message_id
                followup_generation: int | None = int(generation)
                attempts = 0
            else:
                # A delivered/handled/failed follow-up belonged to an older message; a new
                # inbound message resets it so a fresh WAIT can be armed.
                followup_state = "none"
                due = None
                followup_message_id = None
                followup_generation = None
                attempts = 0
            conn.execute(
                "UPDATE watch SET last_message_id = ?, last_message_at = ?, followup_state = ?, "
                "followup_due = ?, followup_message_id = ?, followup_generation = ?, "
                "followup_attempts = ?, followup_armed_at = ? WHERE id = 1",
                (message_id, now, followup_state, due, followup_message_id, followup_generation,
                 attempts, now if followup_state == "pending" else None),
            )
            conn.commit()
        except Exception:
            conn.rollback()
            raise


def arm_followup(session_key: str, session_id: str, message_id: Any) -> dict[str, Any]:
    """Arm exactly one pending follow-up for the latest delivered watched message."""
    if not _enabled():
        raise WatchError("watch is disabled")
    if not isinstance(session_key, str) or not session_key.strip() or not isinstance(session_id, str) or not session_id.strip():
        raise WatchError("no trusted session context; run this from a gateway conversation")
    mid = _clean(message_id, "message_id")
    if not _ensure_supervisor_sync():
        raise WatchError("follow-up scheduler is not running; no live in-process gateway has this watch")
    now = _now()
    with _db() as conn:
        try:
            conn.execute("BEGIN IMMEDIATE")
            row = _read_watch(conn, now)
            if row is None:
                raise WatchError("no active watch")
            if row["session_key"] != session_key:
                raise WatchError("another session owns the active watch; only that session can wait")
            if row["session_id"] != session_id:
                raise WatchError("watch is pinned to a previous session; re-arm it before waiting")
            if row["last_message_id"] is None:
                raise WatchError("no watched message has been delivered yet")
            if mid != row["last_message_id"]:
                raise WatchError(f"stale message id; the latest watched message is {row['last_message_id']}")
            state = str(row["followup_state"] or "none")
            same = row["followup_message_id"] == mid
            if state == "delivered" and same:
                raise WatchError("a follow-up was already delivered for this message; wait for a newer inbound message")
            if state == "handled" and same:
                raise WatchError("this message was already handled; wait for a newer inbound message")
            if state == "failed" and same:
                raise WatchError("the follow-up for this message already failed; wait for a newer inbound message")
            if state == "pending" and same:
                due = float(row["followup_due"])
                generation = int(row["generation"])
                conn.commit()
                return {
                    "watch_ref": _watch_ref(row),
                    "generation": generation,
                    "message_id": mid,
                    "due": due,
                    "due_iso": _iso(due),
                    "already_armed": True,
                }
            due = float(row["last_message_at"] or now) + FOLLOWUP_SECONDS
            generation = int(row["generation"])
            conn.execute(
                "UPDATE watch SET followup_state = 'pending', followup_due = ?, followup_message_id = ?, "
                "followup_generation = ?, followup_attempts = 0, followup_armed_at = ? WHERE id = 1",
                (due, mid, generation, now),
            )
            conn.commit()
        except Exception:
            conn.rollback()
            raise
    _wake_supervisor()
    return {
        "watch_ref": _watch_ref(row),
        "generation": generation,
        "message_id": mid,
        "due": due,
        "due_iso": _iso(due),
        "already_armed": False,
    }


def mark_handled(session_key: str, session_id: str, message_id: Any) -> str:
    """Cancel a pending follow-up for this exact message and close its token."""
    if not _enabled():
        raise WatchError("watch is disabled")
    if not isinstance(session_key, str) or not session_key.strip() or not isinstance(session_id, str) or not session_id.strip():
        raise WatchError("no trusted session context; run this from a gateway conversation")
    mid = _clean(message_id, "message_id")
    now = _now()
    with _db() as conn:
        try:
            conn.execute("BEGIN IMMEDIATE")
            row = _read_watch(conn, now)
            if row is None:
                raise WatchError("no active watch")
            if row["session_key"] != session_key:
                raise WatchError("another session owns the active watch; only that session can report handled")
            if row["session_id"] != session_id:
                raise WatchError("watch is pinned to a previous session; re-arm it before reporting handled")
            if mid != row["last_message_id"]:
                raise WatchError(f"stale message id; the latest watched message is {row['last_message_id']}")
            state = str(row["followup_state"] or "none")
            if state == "pending" and row["followup_message_id"] != mid:
                raise WatchError(
                    f"stale follow-up token; pending message is {row['followup_message_id']}"
                )
            if state == "delivering" and row["followup_message_id"] == mid:
                raise WatchError("the follow-up is being delivered; retry handled after it completes")
            conn.execute(
                "UPDATE watch SET followup_state = 'handled', followup_due = NULL, "
                "followup_message_id = ?, followup_generation = ?, followup_attempts = 0 WHERE id = 1",
                (mid, int(row["generation"])),
            )
            conn.commit()
        except Exception:
            conn.rollback()
            raise
    _wake_supervisor()
    return f"handled message {mid} (generation {int(row['generation'])})"


def _claim_followup(generation: int, message_id: str) -> sqlite3.Row | None:
    now = _now()
    with _db() as conn:
        try:
            conn.execute("BEGIN IMMEDIATE")
            row = _read_watch(conn, now)
            if row is None:
                conn.rollback()
                return None
            if int(row["generation"]) != int(generation):
                conn.rollback()
                return None
            if row["followup_state"] != "pending" or row["followup_message_id"] != message_id:
                conn.rollback()
                return None
            if row["followup_due"] is None or float(row["followup_due"]) > now:
                conn.rollback()
                return None
            conn.execute(
                "UPDATE watch SET followup_state = 'delivering', "
                "followup_attempts = followup_attempts + 1 WHERE id = 1"
            )
            conn.commit()
            return row
        except Exception:
            conn.rollback()
            raise


def _finish_followup(generation: int, message_id: str, state: str) -> None:
    with _db() as conn:
        conn.execute(
            "UPDATE watch SET followup_state = ?, followup_due = NULL "
            "WHERE id = 1 AND generation = ? AND followup_message_id = ? AND followup_state = 'delivering'",
            (state, int(generation), message_id),
        )


def _retry_followup(generation: int, message_id: str) -> str:
    now = _now()
    with _db() as conn:
        try:
            conn.execute("BEGIN IMMEDIATE")
            row = _read_watch(conn, now)
            if row is None or int(row["generation"]) != int(generation) or row["followup_message_id"] != message_id:
                conn.commit()
                return "stale"
            if row["followup_state"] != "delivering":
                conn.commit()
                return "stale"
            attempts = int(row["followup_attempts"])
            if attempts >= FOLLOWUP_MAX_ATTEMPTS:
                conn.execute(
                    "UPDATE watch SET followup_state = 'failed', followup_due = NULL WHERE id = 1"
                )
                state = "failed"
            else:
                conn.execute(
                    "UPDATE watch SET followup_state = 'pending', followup_due = ? WHERE id = 1",
                    (now + FOLLOWUP_RETRY_SECONDS,),
                )
                state = "pending"
            conn.commit()
            return state
        except Exception:
            conn.rollback()
            raise


def _followup_current(generation: int, message_id: str) -> bool:
    """True only while the claimed follow-up still owns the watch row."""
    try:
        row = _active_watch()
    except Exception:
        return False
    return bool(
        row is not None
        and int(row["generation"]) == int(generation)
        and row["followup_state"] == "delivering"
        and row["followup_message_id"] == message_id
    )


def _internal_notification(text: str) -> str:
    """Append the host's native internal-notification provenance footer."""
    try:
        from gateway.run_notifications import _mark_internal_notification

        return _mark_internal_notification(text)
    except Exception:
        text = text.rstrip()
        if text.endswith(INTERNAL_NOTIFICATION_FOOTER):
            return text
        return text + "\n\n" + INTERNAL_NOTIFICATION_FOOTER


